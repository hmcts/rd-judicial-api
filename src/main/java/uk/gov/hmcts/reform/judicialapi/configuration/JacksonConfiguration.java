package uk.gov.hmcts.reform.judicialapi.configuration;

import org.springframework.boot.jackson.autoconfigure.JsonMapperBuilderCustomizer;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;
import tools.jackson.databind.DeserializationFeature;
import tools.jackson.databind.cfg.ConstructorDetector;
import tools.jackson.databind.cfg.DateTimeFeature;

@Configuration
public class JacksonConfiguration {

    /**
     * Preserve Boot 3 JSON contracts on the Jackson 3 mapper used by MVC and Feign.
     * Unknown properties stay ignored, omitted primitive values stay at their Java defaults,
     * and dates stay ISO-8601 strings. The all-args constructors generated by Lombok are not
     * treated as JSON creators when a no-arg constructor is also present.
     *
     * @return customizer applied to Boot's {@code JsonMapper}
     */
    @Bean
    public JsonMapperBuilderCustomizer judicialJsonMapperCustomizer() {
        return builder -> builder
            .disable(DeserializationFeature.FAIL_ON_UNKNOWN_PROPERTIES)
            .disable(DeserializationFeature.FAIL_ON_NULL_FOR_PRIMITIVES)
            .disable(DateTimeFeature.WRITE_DATES_AS_TIMESTAMPS)
            .constructorDetector(
                ConstructorDetector.DEFAULT.withAllowImplicitWithDefaultConstructor(false));
    }
}
